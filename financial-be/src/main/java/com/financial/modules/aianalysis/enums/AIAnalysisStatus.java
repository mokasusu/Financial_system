package com.financial.modules.aianalysis.enums;

import io.swagger.v3.oas.annotations.media.Schema;
import lombok.Getter;

@Getter
@Schema(description = "Lifecycle processing status of AI financial analysis")
public enum AIAnalysisStatus {

    @Schema(description = "Analysis request received and queued")
    PENDING("Đang chờ xử lý"),

    @Schema(description = "Analysis is currently being generated by AI provider")
    PROCESSING("Đang phân tích AI"),

    @Schema(description = "AI analysis generated, parsed, and persisted successfully")
    COMPLETED("Hoàn thành phân tích"),

    @Schema(description = "AI analysis generation or parsing failed")
    FAILED("Phân tích thất bại");

    private final String displayName;

    AIAnalysisStatus(String displayName) {
        this.displayName = displayName;
    }
}

